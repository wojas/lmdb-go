#!/bin/sh
# Refresh tests/cgolmdb: a pinned copy of lmdb-go v1's lmdb package (cgo,
# with its bundled C LMDB 0.9) under its own import path, so that tests and
# benchmarks in the tests/ module can use the original cgo implementation
# and the port side by side in one binary. Only the non-test sources are
# copied; the import of the internal lmdbarch package is rewritten to the
# copy under tests/internal. Never edit the copy by hand.
#
# Usage: scripts/update-cgolmdb.sh [git ref]   (default: see below)
#
# The default is e5af975, "Upgrade upstream LMDB to 0.9.36 (mdb.RE/0.9 at
# a69ce88)", on the upstream branch freelist-split-experiment: one commit on
# top of lmdb-go v1.9.4 (1fef05e) that changes only the C sources, so the Go
# code is v1.9.4's. Its C code is LMDB 0.9.36 plus ITS#10615, ITS#10642 and
# ITS#10643, the same code as LMDB 0.9.37 (its lmdb.h says 0.9.36). The
# released lmdb-go v1.9.4 bundles C LMDB 0.9.35.
set -eu
default_ref=e5af975
ref=${1:-$default_ref}
repo=$(cd "$(dirname "$0")/.." && pwd)
dst=$repo/tests/cgolmdb
arch=$repo/tests/internal/lmdbarch
rm -rf "$dst" "$arch"
mkdir -p "$dst" "$arch"
cd "$repo"
for f in $(git ls-tree --name-only "$ref" lmdb/); do
  case $f in *_test.go) continue ;; esac
  git show "$ref:$f" > "$dst/$(basename "$f")"
done
for f in $(git ls-tree --name-only "$ref" internal/lmdbarch/); do
  git show "$ref:$f" > "$arch/$(basename "$f")"
done
for f in "$dst"/*.go; do
  sed 's#"github.com/PowerDNS/lmdb-go/internal/lmdbarch"#"github.com/PowerDNS/lmdb-go/tests/internal/lmdbarch"#' "$f" > "$f.tmp"
  mv "$f.tmp" "$f"
done
# The C version comes from the copied header, so that another ref cannot
# leave a wrong statement here; the fixes on top are known for the default.
c_version=$(awk '/#define MDB_VERSION_(MAJOR|MINOR|PATCH)/ { v = v (v == "" ? "" : ".") $3 } END { print v }' "$dst/lmdb.h")
c_extra=
if [ "$ref" = "$default_ref" ]; then
  c_extra=" plus ITS#10615, ITS#10642 and ITS#10643,
the same code as LMDB 0.9.37"
fi
cat > "$dst/README.md" <<EOT
# cgolmdb

A copy of the \`lmdb\` package of lmdb-go at \`$ref\` (cgo), generated by
\`scripts/update-cgolmdb.sh\`. Do not edit. Its C library is
LMDB $c_version$c_extra.
It is the reference the tests and benchmarks in this module compare the
port with. Import it as:

    import cgolmdb "github.com/PowerDNS/lmdb-go/tests/cgolmdb"

The Go sources are lmdb-go's (see \`LICENSE.md\` at the repository root); the
C sources are LMDB's, under the OpenLDAP Public License (\`LICENSE.mdb.md\`
at the repository root; the C files keep their own headers).
EOT
echo "tests/cgolmdb refreshed from $ref ($(git rev-parse --short "$ref^{commit}"))"
