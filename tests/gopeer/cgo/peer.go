// Package peer is the Go peer of rlmdb's interop harness: it speaks the
// peer command protocol of rlmdb's interop/README.md ("The peer
// command protocol"), so that the harness can run Go processes next to C
// LMDB 0.9 (cpeer), C LMDB 1.0 (cpeer10), rlmdb (rpeer) and C on rlmdb
// (cpeer_capi) on one environment. The command gopeer (..) runs it.
//
// It is a port of the C peer (interop/c/cpeer*.c), file by file, to
// lmdb-go's API. This package (gopeer/cgo) is the source and runs on the
// pinned cgo reference (lmdb-go v1.9.4's Go code on C LMDB 0.9.36 plus
// ITS#10615, ITS#10642 and ITS#10643); gopeer/port is the same code on
// the Go implementation, generated by tests/gen-port.sh. The same LMDB
// calls in the same order, the same output:
//
//	peer.go      cpeer.c           command line, exit codes, env open
//	dataset.go   dataset.c         the deterministic data set
//	data.go      cpeer_data.c      fill, verify, delete, drop, dump
//	loops.go     cpeer_loops.c     hold-reader, hold-env, hold-writer, writer-loop, reader-loop
//	misc.go      cpeer_misc.c      create, stat, readers, reader-check, copy, nested-test, gen
//	pagewalk.go  cpeer_pagewalk.c  check-freelist
//	impl.go      -                 what differs between the implementations (hand-written per side)
//
// Where lmdb-go's API cannot express a C call, the command does the
// closest equivalent and says so on stderr with a NOT-IMPLEMENTED line (the
// harness reports those as "SKIPPED partly"); commands it cannot do at all
// exit with status 4. ../README.md lists them.
package peer

import (
	"bufio"
	"errors"
	"fmt"
	"math"
	"os"
	"runtime"
	"strconv"
	"strings"
	"syscall"
	"time"

	lmdb "github.com/PowerDNS/lmdb-go/tests/cgolmdb"
)

// Exit codes of every command.
const (
	exitMismatch       = 1 // a data or invariant check failed
	exitUsage          = 2 // bad command line
	exitLMDB           = 3 // an LMDB call failed unexpectedly
	exitNotImplemented = 4 // command not implemented by this peer
)

// stdout is flushed after every printf: the harness waits for READY lines
// (C's peer uses setvbuf(_IOLBF)).
var stdout = bufio.NewWriterSize(os.Stdout, 1<<16)

func printf(format string, a ...any) {
	fmt.Fprintf(stdout, format, a...)
	stdout.Flush()
}

// writeTxn is the open top-level write transaction, if any. die aborts it
// so that a failing peer releases the writer lock instead of leaving other
// processes blocked on it (named semaphores, used on macOS, are not
// robust).
var writeTxn *lmdb.Txn

// beginWrite begins a top-level write transaction. The main goroutine is
// locked to its thread (init), as lmdb-go requires for write
// transactions.
func beginWrite(env *lmdb.Env) *lmdb.Txn {
	txn, err := env.BeginTxn(nil, 0)
	check(err, "mdb_txn_begin")
	writeTxn = txn
	return txn
}

func commitWrite(txn *lmdb.Txn) {
	writeTxn = nil
	check(txn.Commit(), "mdb_txn_commit")
}

func abortWrite(txn *lmdb.Txn) {
	writeTxn = nil
	txn.Abort()
}

// beginRead begins a read-only transaction.
//
// Transactions keep lmdb-go's default RawRead = false (values are copied
// out of the map): with RawRead = true, lmdb-go v1's Cursor.Get panics
// (nil pointer) after the ops for which C leaves the key unset
// (MDB_FIRST_DUP, MDB_LAST_DUP), because it slices the NULL mv_data.
func beginRead(env *lmdb.Env) *lmdb.Txn {
	txn, err := env.BeginTxn(nil, lmdb.Readonly)
	check(err, "mdb_txn_begin")
	return txn
}

// beginChild begins a nested write transaction.
func beginChild(env *lmdb.Env, parent *lmdb.Txn) *lmdb.Txn {
	txn, err := env.BeginTxn(parent, 0)
	check(err, "mdb_txn_begin(child)")
	return txn
}

// die prints a message to stderr (prefixed "gopeer: ") and exits with
// code, aborting the open write transaction first.
func die(code int, format string, a ...any) {
	if writeTxn != nil {
		txn := writeTxn
		writeTxn = nil
		txn.Abort()
	}
	stdout.Flush()
	fmt.Fprintf(os.Stderr, "gopeer: "+format+"\n", a...)
	os.Exit(code)
}

// check exits with exitLMDB if err is not nil, naming the failed call.
func check(err error, what string) {
	if err != nil {
		die(exitLMDB, "%s failed: %s", what, errText(err))
	}
}

// errText formats an LMDB error as C's peer does: "<code> <strerror>".
// lmdb-go wraps return codes in *OpError: an lmdb.Errno (MDB_* codes, with
// mdb_strerror's text) or a syscall.Errno, whose Go text is lower case
// where strerror's is capitalised ("Function not implemented", which the
// harness looks for when the port lacks something).
func errText(err error) string {
	var op *lmdb.OpError
	if errors.As(err, &op) {
		switch e := op.Errno.(type) {
		case lmdb.Errno:
			return fmt.Sprintf("%d %s", int(e), e.Error())
		case syscall.Errno:
			s := e.Error()
			if s != "" {
				s = strings.ToUpper(s[:1]) + s[1:]
			}
			return fmt.Sprintf("%d %s", int(e), s)
		}
	}
	return err.Error()
}

// isErr tells whether err is the LMDB error code e.
func isErr(err error, e lmdb.Errno) bool { return lmdb.IsErrno(err, e) }

// opts is the parsed command line (struct opts of cpeer.h).
type opts struct {
	cmd string
	pos []string // positional arguments after the command

	// environment options, valid for every command
	nosubdir, notls, nosync, nometasync bool
	mapsize                             uint64 // 0: keep the environment's size
	maxdbs, maxreaders                  uint32
	format                              int    // --format: 0 (not given), 9 (0.9) or 10 (1.0)
	pagesize                            uint32 // --pagesize (LMDB 1.0): 0, or a new env's page size

	// data set and command options
	ds                                            dataset
	perTxn                                        uint32 // fill/delete: items per transaction, 0 = all
	every                                         uint32 // delete --every
	appendMode, reserve, compact, all, untilStdin bool
	checkMode                                     bool // nested-test --check
	del                                           bool // drop --delete
	keys                                          uint32
	maxCommits                                    uint64
}

func parseU64(s *string, what string) uint64 {
	if s == nil || *s == "" {
		die(exitUsage, "missing %s", what)
	}
	v, err := strconv.ParseUint(*s, 0, 64)
	if err != nil {
		die(exitUsage, "bad %s: '%s'", what, *s)
	}
	return v
}

func parseU32(s *string, what string) uint32 {
	v := parseU64(s, what)
	if v > math.MaxUint32 {
		die(exitUsage, "%s out of range: '%s'", what, *s)
	}
	return uint32(v)
}

func parseSeconds(s *string) float64 {
	if s == nil {
		die(exitUsage, "missing seconds")
	}
	v, err := strconv.ParseFloat(*s, 64)
	if err != nil || v < 0 {
		die(exitUsage, "bad seconds: '%s'", *s)
	}
	return v
}

// pos returns positional argument k, or nil.
func (o *opts) posArg(k int) *string {
	if k < len(o.pos) {
		return &o.pos[k]
	}
	return nil
}

// dbArg is the DB name of positional argument k: "" for "-" (the main DB).
func (o *opts) dbArg(k int) string {
	if o.pos[k] == "-" {
		return ""
	}
	return o.pos[k]
}

// dbLabel is the DB name as printed in outputs: "-" for the main DB.
func dbLabel(db string) string {
	if db == "" {
		return "-"
	}
	return db
}

var start = time.Now()

// nowSeconds is a monotonic clock in seconds.
func nowSeconds() float64 { return time.Since(start).Seconds() }

func sleepSeconds(s float64) {
	if s > 0 {
		time.Sleep(time.Duration(s * 1e9))
	}
}

// parseFormat checks --format 0.9|1.0 against what this implementation
// opens: lmdb-go v1 opens the 0.9 format only and refuses 1.0 with a usage
// error, as cpeer does; the port opens both.
func parseFormat(s string) int {
	var f int
	switch s {
	case "0.9":
		f = 9
	case "1.0":
		f = 10
	default:
		die(exitUsage, "bad --format '%s' (0.9 or 1.0)", s)
	}
	if f == 10 && !supportsFormat10 {
		die(exitUsage, "--format %s: this peer runs on %s and opens only the LMDB 0.9 format",
			s, implName())
	}
	return f
}

// openEnv opens the environment named by o.pos[0] with the global options.
// The --notls flag is accepted, but lmdb-go always opens environments with
// MDB_NOTLS (Env.Open adds it), so read transactions always behave like
// MDB_NOTLS ones, as rpeer's do.
func openEnv(o *opts, extra uint) *lmdb.Env {
	flags := extra
	if o.nosubdir {
		flags |= lmdb.NoSubdir
	}
	if o.notls {
		flags |= lmdb.NoTLS
	}
	if o.nosync {
		flags |= lmdb.NoSync
	}
	if o.nometasync {
		flags |= lmdb.NoMetaSync
	}
	env, err := lmdb.NewEnv()
	check(err, "mdb_env_create")
	switch o.format {
	case 9:
		check(setFormat(env, false), "Env.SetFormat(0.9)")
	case 10:
		check(setFormat(env, true), "Env.SetFormat(1.0)")
	}
	if o.pagesize != 0 {
		check(setPageSize(env, int(o.pagesize)), "Env.SetPageSize")
	}
	if o.mapsize != 0 {
		check(env.SetMapSize(int64(o.mapsize)), "mdb_env_set_mapsize")
	}
	check(env.SetMaxDBs(int(o.maxdbs)), "mdb_env_set_maxdbs")
	if o.maxreaders != 0 {
		check(env.SetMaxReaders(int(o.maxreaders)), "mdb_env_set_maxreaders")
	}
	if err := env.Open(o.pos[0], flags, 0o664); err != nil {
		die(exitLMDB, "mdb_env_open(%s) failed: %s", o.pos[0], errText(err))
	}
	return env
}

// envIs10 tells whether an open env is an LMDB 1.0 environment.
func envIs10(env *lmdb.Env) bool { return isFormat10(env) }

// openDB opens the DB named db ("" for the main DB) in txn: mdb_dbi_open.
func openDB(txn *lmdb.Txn, db string, flags uint) (lmdb.DBI, error) {
	if db == "" {
		return txn.OpenRoot(flags)
	}
	return txn.OpenDBI(db, flags)
}

// subDBName is the name of the named DB whose record in the main DB has
// key key, or false if key cannot be a DB name: a name has no NUL byte,
// and in LMDB 1.0 the key is the name with its terminating NUL (0.9:
// without).
func subDBName(v10 bool, key []byte) (string, bool) {
	if v10 {
		if len(key) == 0 || key[len(key)-1] != 0 {
			return "", false
		}
		key = key[:len(key)-1]
	}
	for _, b := range key {
		if b == 0 {
			return "", false
		}
	}
	return string(key), true
}

// command is one command of the protocol (struct command).
type command struct {
	name           string
	run            func(*opts) int
	minPos, maxPos int // positional arguments incl. <env>
	usage          string
	implemented    bool
}

var commands []command

func init() {
	// Write transactions must stay on one OS thread (lmdb-go's BeginTxn
	// documentation); everything runs on the main goroutine.
	runtime.LockOSThread()
	commands = []command{
		{"create", cmdCreate, 3, 3, "create <env> <mapsize> <maxdbs>", true},
		{"fill", cmdFill, 4, 4, "fill <env> <db|-> <count> <seed> [data options]", true},
		{"verify", cmdVerify, 4, 4, "verify <env> <db|-> <count> <seed> [data options]", true},
		{"delete", cmdDelete, 4, 4, "delete <env> <db|-> <count> <seed> [--every N] [data options]", true},
		{"drop", cmdDrop, 2, 2, "drop <env> <db|-> [--delete]", true},
		{"dump", cmdDump, 1, 2, "dump <env> <db|-> | dump <env> --all", true},
		{"stat", cmdStat, 1, 1, "stat <env>", true},
		{"readers", cmdReaders, 1, 1, "readers <env>", true},
		{"reader-check", cmdReaderCheck, 1, 1, "reader-check <env>", true},
		{"hold-reader", cmdHoldReader, 2, 5,
			"hold-reader <env> <seconds> [--until-stdin] [<db|-> <count> <seed> [data options]]", true},
		{"hold-env", cmdHoldEnv, 2, 2, "hold-env <env> <seconds> [--until-stdin]", true},
		{"hold-writer", cmdHoldWriter, 2, 2, "hold-writer <env> <seconds> [--until-stdin]", true},
		{"writer-loop", cmdWriterLoop, 4, 4,
			"writer-loop <env> <db|-> <seconds> <seed> [--keys N] [--max-commits N]", true},
		{"reader-loop", cmdReaderLoop, 3, 3, "reader-loop <env> <db|-> <seconds>", true},
		{"formats-loop", cmdFormatsLoop, 5, 5,
			"formats-loop <env 0.9> <env 1.0> <db|-> <seconds> <seed> [--keys N] [--max-commits N]", false},
		{"check-freelist", cmdCheckFreelist, 1, 1, "check-freelist <env>", true},
		{"nested-test", cmdNestedTest, 1, 1, "nested-test <env> [--check]", true},
		{"copy", cmdCopy, 2, 2, "copy <env> <dest> [--compact]", true},
		{"gen", cmdGen, 2, 2, "gen <seed> <i> [data options]", true},
		{"commands", cmdCommands, 0, 0, "commands", true},
	}
}

// cmdCommands prints "command=<name> implemented=<0|1>" for every command:
// the harness asks peers what they implement.
func cmdCommands(*opts) int {
	for _, c := range commands {
		impl := 0
		if c.implemented {
			impl = 1
		}
		printf("command=%s implemented=%d\n", c.name, impl)
	}
	return 0
}

// cmdFormatsLoop: an LMDB 0.9 and an LMDB 1.0 environment in one process
// with writer threads; rpeer only, like cpeer (nothing needs it from Go).
func cmdFormatsLoop(*opts) int {
	die(exitNotImplemented, "NOT-IMPLEMENTED formats-loop: not implemented by this peer (rpeer only)")
	return exitNotImplemented
}

func usage() {
	var b strings.Builder
	b.WriteString("usage: gopeer <command> <args...> [options]\ncommands:\n")
	for _, c := range commands {
		b.WriteString("  " + c.usage + "\n")
	}
	b.WriteString("env options: --impl cgo|port --nosubdir --notls --nosync --nometasync --mapsize N" +
		" --maxdbs N --maxreaders N --format 0.9|1.0 --pagesize N\n" +
		"data options: --dupsort --dupfixed --intkey --intdup --revkey --revdup" +
		" --valsize N --big N --dups N --deleted-every N --per-txn N --append --reserve\n")
	fmt.Fprint(os.Stderr, b.String())
	os.Exit(exitUsage)
}

func parseArgs(args []string) *opts {
	o := &opts{maxdbs: 64, every: 2, keys: 500}
	if len(args) < 1 {
		usage()
	}
	o.cmd = args[0]
	for k := 1; k < len(args); k++ {
		a := args[k]
		if !strings.HasPrefix(a, "--") {
			if len(o.pos) == 8 {
				die(exitUsage, "too many arguments")
			}
			o.pos = append(o.pos, a)
			continue
		}
		// The value of an option that takes one.
		val := func() *string {
			if k+1 >= len(args) {
				die(exitUsage, "option %s needs a value", a)
			}
			k++
			return &args[k]
		}
		switch a {
		// environment options
		case "--nosubdir":
			o.nosubdir = true
		case "--notls":
			o.notls = true
		case "--nosync":
			o.nosync = true
		case "--nometasync":
			o.nometasync = true
		case "--mapsize":
			o.mapsize = parseU64(val(), a)
		case "--maxdbs":
			o.maxdbs = parseU32(val(), a)
		case "--maxreaders":
			o.maxreaders = parseU32(val(), a)
		case "--format":
			o.format = parseFormat(*val())
		case "--pagesize":
			o.pagesize = parseU32(val(), a)
			if !supportsFormat10 {
				die(exitUsage, "--pagesize: LMDB 0.9 has no mdb_env_set_pagesize")
			}
		// data set options
		case "--dupsort":
			o.ds.dbflags |= lmdb.DupSort
		case "--dupfixed":
			o.ds.dbflags |= lmdb.DupSort | lmdb.DupFixed
		case "--intkey":
			o.ds.dbflags |= lmdb.IntegerKey
		case "--intdup":
			o.ds.dbflags |= lmdb.DupSort | lmdb.DupFixed | lmdb.IntegerDup
		case "--revkey":
			o.ds.dbflags |= lmdb.ReverseKey
		case "--revdup":
			o.ds.dbflags |= lmdb.DupSort | lmdb.ReverseDup
		case "--valsize":
			o.ds.valsize = parseU32(val(), a)
		case "--big":
			o.ds.big = parseU32(val(), a)
		case "--dups":
			o.ds.dups = parseU32(val(), a)
		case "--deleted-every":
			o.ds.deletedEvery = parseU32(val(), a)
		// command options
		case "--per-txn":
			o.perTxn = parseU32(val(), a)
		case "--every":
			o.every = parseU32(val(), a)
		case "--keys":
			o.keys = parseU32(val(), a)
		case "--max-commits":
			o.maxCommits = parseU64(val(), a)
		case "--append":
			o.appendMode = true
		case "--reserve":
			o.reserve = true
		case "--compact":
			o.compact = true
		case "--all":
			o.all = true
		case "--until-stdin":
			o.untilStdin = true
		case "--check":
			o.checkMode = true
		case "--delete":
			o.del = true
		default:
			die(exitUsage, "unknown option %s", a)
		}
	}
	return o
}

// parseDatasetArgs fills o.ds from the positional arguments <db|-> <count>
// <seed> that start at o.pos[first].
func parseDatasetArgs(o *opts, first int) {
	o.ds.db = o.dbArg(first)
	o.ds.count = parseU32(o.posArg(first+1), "count")
	o.ds.seed = parseU32(o.posArg(first+2), "seed")
	if err := o.ds.finish(); err != "" {
		die(exitUsage, "%s", err)
	}
}

// Main runs the command line args (without the program name and the
// --impl option of gopeer) and returns the exit status. Commands that fail
// exit the process themselves (die), as C's peer does.
func Main(args []string) int {
	o := parseArgs(args)
	for _, c := range commands {
		if c.name != o.cmd {
			continue
		}
		if len(o.pos) < c.minPos || len(o.pos) > c.maxPos {
			die(exitUsage, "usage: gopeer %s", c.usage)
		}
		code := c.run(o)
		stdout.Flush()
		return code
	}
	if o.cmd != "help" && o.cmd != "--help" {
		fmt.Fprintf(os.Stderr, "gopeer: unknown command '%s'\n", o.cmd)
	}
	usage()
	return exitUsage
}
