#!/bin/sh
# Writes the port twin of a package written against the cgo reference.
#
# Code that runs on both implementations is written once, in <dir>/cgo,
# importing the pinned cgo lmdb-go as
#
#	lmdb "github.com/PowerDNS/lmdb-go/tests/cgolmdb"
#
# (in an import group of its own, so that the rewritten import stays
# sorted for gofmt), and this script writes <dir>/port: the same files
# importing the port (github.com/PowerDNS/lmdb-go/lmdb) instead. The two
# packages have the same API but distinct types, so each is compiled
# against its implementation directly, without interfaces in between. Not copied: tests (*_test.go)
# and impl.go, the one hand-written file per side for what differs (the
# implementation's name, the LMDB 1.0 calls that only the port has).
#
# The twin has the build constraint `port` until the port's lmdb package
# compiles (stage 2): build with -tags port to include it. Stage 2 deletes
# the constraint here and in the hand-written port/impl.go files.
#
# Usage: tests/gen-port.sh <dir> [<out dir>]   (go generate runs it)
set -eu
dir=$1
out=${2:-$dir/port}
mkdir -p "$out"
for f in "$out"/*.go; do
	case $f in */impl.go | */*_test.go) ;; *) rm -f "$f" ;; esac
done
for f in "$dir"/cgo/*.go; do
	name=$(basename "$f")
	case $name in impl.go | *_test.go) continue ;; esac
	{
		echo "// Code generated by tests/gen-port.sh from cgo/$name. DO NOT EDIT."
		echo
		echo "//go:build port"
		echo
		sed 's#^\([[:space:]]*\)lmdb "github.com/PowerDNS/lmdb-go/tests/cgolmdb"$#\1lmdb "github.com/PowerDNS/lmdb-go/lmdb"#' "$f"
	} > "$out/$name"
done
